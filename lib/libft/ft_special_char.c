#include "libft.h"

int	ft_special_char(char *str)
{
	int	i;

	if (!str)
		return (0);
	i = 0;
	while (str[i])
	{
		if (str[i] >= 9 && str[i] <= 13)
			return (1);
		i++;
	}
	return (0);
}
